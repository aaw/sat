#!/usr/bin/python3

# Usage: python3 tseitin-odd-charge-graph.py n d --seed=123
#
# Generates a boolean formula that describes a d-regular graph on n vertices
# and variables associated with each edge. The formula asserts that the sum
# (mod 2) of the variables associateed with edges adjacent to the first vertex
# is 1. For all other vertices, the formula asserts that the sum (mod 2) of
# adjacent edges is 0. This is impossible by the handshaking lemma, so the
# formula is unsatisfiable.

import argparse
import collections
import io
import itertools
import random
import sys

def build_graph(n, d):
    g = collections.defaultdict(set)
    need_edges = set(range(n))
    no_progress = 0
    while need_edges:
        if no_progress > 3 or len(need_edges) == 1:
            while True:
                u = random.randrange(n)
                if len(g[u]) == 0: continue
                v = random.choice(sorted(g[u]))
                g[u].remove(v)
                g[v].remove(u)
                need_edges.add(u)
                need_edges.add(v)
                break
            no_progress = 0
        u, v = random.sample(sorted(need_edges), 2)
        no_progress += 1
        if u in g[v]: continue  # Don't add an edge twice
        g[u].add(v)
        g[v].add(u)
        if len(g[u]) == d: need_edges.remove(u)
        if len(g[v]) == d: need_edges.remove(v)
        no_progress = 0
    return g


def gen_odd_charge(n, d):
    def edge_var(u, v, index):
        if u > v: u,v = v,u
        if (u,v) in index:
            return index[(u,v)]
        next_index = max(index.values(), default=0) + 1
        index[(u,v)] = next_index
        return next_index

    def assert_even_sum(varz):
        for k in range(1, n+1, 2):  # odd k
            for subset in itertools.combinations(varz, k):
                sign = {x: (-1 if x in subset else 1) for x in varz}
                yield [sign[v]*v for v in varz]

    def assert_odd_sum(varz):
        for k in range(0, n+1, 2):  # even k
            for subset in itertools.combinations(varz, k):
                sign = {x: (-1 if x in subset else 1) for x in varz}
                yield [sign[v]*v for v in varz]

    g = build_graph(n, d)

    clauses = []
    edge_index = {}
    # Assert that the sum of edge vars adjacent to vertex 0 is odd.
    for clause in assert_odd_sum([edge_var(0,x,edge_index) for x in g[0]]):
        clauses.append(clause)

    # Assert that the sum of edge vars adjacent to any vertex > 0 is even.
    for v in range(1,n):
        for clause in assert_even_sum([edge_var(v,x,edge_index) for x in g[v]]):
            clauses.append(clause)

    buffer = io.StringIO()
    for c in clauses:
        buffer.write((" ".join(["{}"] * len(c)) + " 0\n").format(*c))

    return 'p cnf {0} {1}\n'.format(len(edge_index), len(clauses)) + buffer.getvalue()

if __name__ == '__main__':
    parser = argparse.ArgumentParser(
        description="Generate an unsatisfiable Tseiten formula over a random graph")
    parser.add_argument('n', type=int, help='Number of vertices')
    parser.add_argument('d', type=int, help='Degree of graph')
    parser.add_argument('--seed', type=int, default=None, help='Random seed')
    args = parser.parse_args()
    assert (args.n * args.d % 2 == 0), "Product of n * d must be even."

    print("c Generated by tseitin-odd-charge-graph.py {0}".format(' '.join(sys.argv[1:])))
    print("c Generator source: " +
          "https://github.com/aaw/sat/blob/master/gen/tseitin-odd-charge-graph.py")
    print("c label:unsatisfiable")

    if args.seed is not None:
        random.seed(args.seed)
    print(gen_odd_charge(args.n, args.d))
