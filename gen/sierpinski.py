#!/usr/bin/python3

# Usage: python3 sierpinski.py n [--pinched]
#
# Generates a boolean formula that asserts that the Sierpinski gasket graph
# S_n^(3) can be 3-colored, as described in TAOCP 7.2.2.3, Fig. 113. Vertices
# are labeled by ternary strings a_1...a_n. Each ternary string a_1...a_{n-1}
# labels a triangle whose corners are a_1...a_{n-1}0, a_1...a_{n-1}1, and
# a_1...a_{n-1}2. Every vertex whose label has the form
# a_1...a_{k-1} a_k a_n...a_n with a_k != a_n is identified with the vertex
# labeled a_1...a_{k-1} a_n a_k...a_k, so there are (3^n + 3)/2 distinct
# vertices. The formula is satisfiable for all n.
#
# Passing --pinched merges the corners 0...0 and 1...1 into a single vertex of
# degree 4. Every 3-coloring of S_n^(3) gives its three corners distinct colors,
# so the pinched formula is unsatisfiable.

import argparse
import io
import itertools
import sys

def canonical(label):
    # Returns the smaller of label and the label it's identified with.
    n = len(label)
    last = label[-1]
    k = n - 1
    while k >= 0 and label[k] == last: k -= 1
    if k < 0: return label  # Corner of the whole gasket; no twin.
    twin = label[:k] + (last,) + (label[k],) * (n - k - 1)
    return min(label, twin)

def build_graph(n, pinched):
    vertex_index = {}
    def vertex(label):
        label = canonical(label)
        if pinched and label == (1,) * n: label = (0,) * n
        if label not in vertex_index:
            vertex_index[label] = len(vertex_index)
        return vertex_index[label]

    edges = []
    for alpha in itertools.product(range(3), repeat=n-1):
        corners = [vertex(alpha + (i,)) for i in range(3)]
        for u, v in itertools.combinations(corners, 2):
            edges.append((u, v))
    return len(vertex_index), edges

def gen_sierpinski(n, pinched):
    d = 3  # Number of colors available
    num_vertices, edges = build_graph(n, pinched)
    assert num_vertices == (3**n + 3) // 2 - (1 if pinched else 0)

    # Variable v(i,c) asserts vertex i is colored c.
    def v(i, c):
        return i*d + c + 1

    clauses = []
    # Assert that every vertex is colored.
    for i in range(num_vertices):
        clauses.append([v(i,c) for c in range(d)])

    # Assert that edges can't connect vertices of the same color.
    for i, j in edges:
        for c in range(d):
            clauses.append([-v(i,c), -v(j,c)])

    buffer = io.StringIO()
    for c in clauses:
        buffer.write((" ".join(["{}"] * len(c)) + " 0\n").format(*c))

    return 'p cnf {0} {1}\n'.format(num_vertices * d, len(clauses)) + buffer.getvalue()

if __name__ == '__main__':
    parser = argparse.ArgumentParser(
        description="Generate a formula asserting the Sierpinski gasket graph is 3-colorable")
    parser.add_argument('n', type=int, help='Order of the Sierpinski gasket graph')
    parser.add_argument('--pinched', action='store_true',
                        help='Merge the 0...0 and 1...1 corners into one vertex')
    args = parser.parse_args()
    assert args.n > 0, "n must be positive."
    assert not args.pinched or args.n > 1, "n must be at least 2 when pinched."

    print("c Generated by sierpinski.py {0}".format(' '.join(sys.argv[1:])))
    print("c Generator source: " +
          "https://github.com/aaw/sat/blob/master/gen/sierpinski.py")
    if args.pinched:
        print("c label:unsatisfiable")
    else:
        print("c label:satisfiable")
    print(gen_sierpinski(args.n, args.pinched))
